-- YEAR granularity: yearly settlement archive, 5 years.
CREATE TABLE system.YEARLY_SETTLEMENT
(
    SETTLEMENT_ID   NUMBER NOT NULL,
    SETTLE_DATE     DATE NOT NULL,
    BRANCH_CODE     VARCHAR2(10),
    TOTAL_AMOUNT    NUMBER(14,2)
)
PARTITION BY RANGE (SETTLE_DATE)
(
    PARTITION YEARLY_SETTLEMENT_P2022 VALUES LESS THAN (TO_DATE('2023-01-01','YYYY-MM-DD')),
    PARTITION YEARLY_SETTLEMENT_P2023 VALUES LESS THAN (TO_DATE('2024-01-01','YYYY-MM-DD')),
    PARTITION YEARLY_SETTLEMENT_P2024 VALUES LESS THAN (TO_DATE('2025-01-01','YYYY-MM-DD')),
    PARTITION YEARLY_SETTLEMENT_P2025 VALUES LESS THAN (TO_DATE('2026-01-01','YYYY-MM-DD')),
    PARTITION YEARLY_SETTLEMENT_P2026 VALUES LESS THAN (TO_DATE('2027-01-01','YYYY-MM-DD')),
    PARTITION YEARLY_SETTLEMENT_PMAX  VALUES LESS THAN (MAXVALUE)
);

INSERT INTO system.YEARLY_SETTLEMENT (SETTLEMENT_ID, SETTLE_DATE, BRANCH_CODE, TOTAL_AMOUNT)
SELECT LEVEL, DATE '2022-01-01' + MOD(LEVEL, 1460), 'BR' || LPAD(MOD(LEVEL, 5) + 1, 2, '0'), ROUND(DBMS_RANDOM.VALUE(100000, 9000000), 2)
FROM DUAL CONNECT BY LEVEL <= 1500;

