-- Adds a PGDBA schema with DEL_JOB_TABLE_LIST (the ILM/partition-retention
-- registry the real internal-network DB has) plus real range-partitioned
-- sample tables at day/month/year granularity, so the local test DB has
-- something for the ILM Partition Retention screen to show end to end.
--
-- Only runs automatically on a FRESH container (gvenzl images run
-- container-entrypoint-initdb.d scripts once, on first init). If the data
-- volume already exists, run this file manually instead, e.g.:
--   docker exec -i oracle-daily-monitoring-test sqlplus -s system/<pw>@FREEPDB1 \
--     < docker/initdb/03_ilm_partition_retention.sql

ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE USER pgdba IDENTIFIED BY "PgdbaTest_2026!" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE TO pgdba;

CREATE TABLE pgdba.DEL_JOB_TABLE_LIST
(
    TABLE_OWNER         VARCHAR2(30),
    TABLE_NAME          VARCHAR2(30),
    COMMENTS            VARCHAR2(500),
    WORK_GROUP          VARCHAR2(3),
    STD_COLUMN          VARCHAR2(100),
    START_HIGHVALUE     VARCHAR2(83),
    END_HIGHVALUE       VARCHAR2(100),
    DELETE_CYCLE        VARCHAR2(100),
    RANGE_TYPE          VARCHAR2(20),
    PARTITION_YN        VARCHAR2(2),
    PARTITION_TYPE      VARCHAR2(20),
    OGG_SYNC_YN         VARCHAR2(2),
    STATUS              VARCHAR2(10),
    LAST_DEL_JOB_TIME   TIMESTAMP(6),
    STD_DATE            VARCHAR2(100),
    MEMO                VARCHAR2(4000)
);

-- Three real range-partitioned sample tables under SYSTEM (the account the
-- app's local test DBMS entry connects as) — one each at MONTH / DAY / YEAR
-- partition granularity, with a little data so a "SELECT * " on them isn't empty.

-- MONTH granularity: monthly order log, 6 months.
CREATE TABLE system.ORDER_LOG
(
    ORDER_ID    NUMBER NOT NULL,
    ORDER_DATE  DATE NOT NULL,
    CUSTOMER_ID NUMBER,
    AMOUNT      NUMBER(12,2)
)
PARTITION BY RANGE (ORDER_DATE)
(
    PARTITION ORDER_LOG_P202601 VALUES LESS THAN (TO_DATE('2026-02-01','YYYY-MM-DD')),
    PARTITION ORDER_LOG_P202602 VALUES LESS THAN (TO_DATE('2026-03-01','YYYY-MM-DD')),
    PARTITION ORDER_LOG_P202603 VALUES LESS THAN (TO_DATE('2026-04-01','YYYY-MM-DD')),
    PARTITION ORDER_LOG_P202604 VALUES LESS THAN (TO_DATE('2026-05-01','YYYY-MM-DD')),
    PARTITION ORDER_LOG_P202605 VALUES LESS THAN (TO_DATE('2026-06-01','YYYY-MM-DD')),
    PARTITION ORDER_LOG_PMAX    VALUES LESS THAN (MAXVALUE)
);

INSERT INTO system.ORDER_LOG (ORDER_ID, ORDER_DATE, CUSTOMER_ID, AMOUNT)
SELECT LEVEL, DATE '2026-01-01' + MOD(LEVEL, 150), MOD(LEVEL, 50) + 1, ROUND(DBMS_RANDOM.VALUE(1000, 500000), 2)
FROM DUAL CONNECT BY LEVEL <= 2000;

