-- Data Pump 이관(Export → Import 생성 → 이관 검증): 매핑표와 생성한 Import 작업.
-- add_datapump_bundle.sql 다음에 한 번만 실행하세요. 없으면 "이관 Import" 화면은 "설치 필요"만 표시합니다.

-- REMAP_SCHEMA / REMAP_TABLESPACE 매핑표 (이름 붙여 저장하고 다시 씀)
CREATE TABLE system.datapump_remap_set
(
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name              VARCHAR2(100)  NOT NULL,
    schemas_json      CLOB,          -- [{from, to, keep}]
    tablespaces_json  CLOB,          -- [{from, to, keep}] — keep = "그대로 사용"
    updated_by        VARCHAR2(100),
    updated_at        DATE,
    CONSTRAINT pk_datapump_remap_set PRIMARY KEY (id),
    CONSTRAINT uq_datapump_remap_set_name UNIQUE (name)
);

-- "이 Export로 Import 만들기" 한 번 (원본 Export 묶음 → 대상 DB)
CREATE TABLE system.datapump_migration_plan
(
    plan_id          VARCHAR2(64)   NOT NULL,
    source_dbms_id   NUMBER         NOT NULL,
    bundle_key       VARCHAR2(64)   NOT NULL,  -- Export 묶음 (bundle_id, 묶음이 없는 외부 작업은 H<이력 id>)
    target_dbms_id   NUMBER         NOT NULL,
    total_sets       NUMBER,                   -- 묶음의 덤프 세트 수 (+ 실행 기록 없는 계획 작업)
    omitted          CLOB,                     -- 일부만 골라 빠지는 항목 JSON (사용자가 확인한 목록)
    filter_excluded  CLOB,                     -- Import 필터로 빠지는 테이블 JSON (사용자가 확인한 목록)
    mapping_json     CLOB,
    options_json     CLOB,
    created_by       VARCHAR2(100),
    created_at       DATE,
    CONSTRAINT pk_datapump_migration_plan PRIMARY KEY (plan_id)
);

CREATE INDEX idx_datapump_migration_bundle ON system.datapump_migration_plan (source_dbms_id, bundle_key, created_at);

-- 생성한 Import 작업 (덤프 세트 하나 = 작업 하나). 실행·parfile 저장·실행 후 대조가 모두 이 기준으로 확인한다.
CREATE TABLE system.datapump_migration_job
(
    job_name           VARCHAR2(128)  NOT NULL,
    plan_id            VARCHAR2(64)   NOT NULL,
    job_no             NUMBER,
    export_history_id  NUMBER,        -- 원본 Export 이력 (덤프 세트)
    export_job_name    VARCHAR2(128),
    target_dbms_id     NUMBER         NOT NULL,
    request_json       CLOB,          -- 생성한 요청 (실행 요청은 이것과 같아야 함)
    parfile_text       CLOB,          -- 생성한 parfile (DIRECTORY에 저장할 때 이것과 같아야 함)
    expected_json      CLOB,          -- 기준: Export 로그 행 수, REMAP, 실행 필터 기대값
    dump_files         CLOB,          -- 대상 DIRECTORY에 있어야 할 덤프 파일 [{name, bytes}]
    CONSTRAINT pk_datapump_migration_job PRIMARY KEY (job_name)
);

CREATE INDEX idx_datapump_migration_job_plan ON system.datapump_migration_job (plan_id);
