-- Monitoring > Real-Time: Blocking 체인에서 SUPER_ADMIN이 누른 세션 Kill 기록 (누가, 언제, 어느 DB의 어떤 세션을).
-- 메타데이터 DB에 한 번만 실행하세요. 이 테이블이 없으면 화면은 그대로 동작하지만, 기록을 남길 수 없으므로 Kill은 거절합니다.

CREATE TABLE system.monitoring_session_kill_log
(
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    dbms_id       NUMBER         NOT NULL,
    dbname        VARCHAR2(100),
    inst_id       NUMBER,
    sid           NUMBER,
    serial_num    NUMBER,
    username      VARCHAR2(128),   -- Kill 대상 세션의 DB 계정
    machine       VARCHAR2(256),
    program       VARCHAR2(256),
    sql_id        VARCHAR2(13),
    killed_by     VARCHAR2(100)  NOT NULL,  -- 앱 로그인 계정
    killed_at     DATE           DEFAULT SYSDATE NOT NULL,
    result        VARCHAR2(10)   NOT NULL,  -- OK | FAILED
    message       VARCHAR2(1000),
    CONSTRAINT pk_session_kill_log PRIMARY KEY (id)
);

CREATE INDEX ix_session_kill_log_at ON system.monitoring_session_kill_log (killed_at);
